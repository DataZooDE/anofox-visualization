// The builder assistant's guide (#145): the sections of the dashboards skill
// between `<!-- assist:begin … -->` and `<!-- assist:end -->` (roles, inputs,
// tables, themes, contract plots, worked examples, the design contract,
// templates, diagrams, gotchas), written to web/assist/guide.md. The skill
// stays the one source: its SQL is executed in CI (validate_skills_sql.py),
// and tests/web/assist_test.mjs fails when guide.md is not current.
//
//   node scripts/gen-assist-guide.mjs           write web/assist/guide.md
//   node scripts/gen-assist-guide.mjs --check   exit 1 if it is stale
import { readFileSync, writeFileSync, existsSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const SKILL = "plugins/anofox-visualization/skills/anofox-visualization-dashboards/SKILL.md";
export const GUIDE = "web/assist/guide.md";

// The marked sections of `skill` (its text), joined by a blank line.
export function guideFrom(skill) {
  const parts = [];
  const re = /<!-- assist:begin\b[^>]*-->\n([\s\S]*?)<!-- assist:end -->/g;
  for (let m; (m = re.exec(skill)); ) parts.push(m[1].trim());
  if (!parts.length) throw new Error(`${SKILL}: no <!-- assist:begin --> … <!-- assist:end --> sections`);
  return `<!-- Generated by scripts/gen-assist-guide.mjs from ${SKILL}; do not edit. -->\n\n${parts.join("\n\n")}\n`;
}

export function current() {
  return guideFrom(readFileSync(path.join(root, SKILL), "utf8"));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const want = current();
  const file = path.join(root, GUIDE);
  if (process.argv.includes("--check")) {
    if (!existsSync(file) || readFileSync(file, "utf8") !== want) {
      console.error(`${GUIDE} is stale: run node scripts/gen-assist-guide.mjs`);
      process.exit(1);
    }
    console.log(`${GUIDE}: current`);
  } else {
    writeFileSync(file, want);
    console.log(`wrote ${GUIDE} (${want.length} bytes)`);
  }
}
